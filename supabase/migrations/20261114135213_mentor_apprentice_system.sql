SET lock_timeout = '5s';
SET statement_timeout = '15s';

CREATE TABLE attendance.mentor_relationships (
    relationship_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relationship_uuid varchar(36) NOT NULL UNIQUE,
    mentor_user_id bigint NOT NULL REFERENCES attendance.users(user_id) ON DELETE CASCADE,
    apprentice_user_id bigint NOT NULL REFERENCES attendance.users(user_id) ON DELETE CASCADE,
    mentor_read_message_id bigint NOT NULL DEFAULT 0,
    apprentice_read_message_id bigint NOT NULL DEFAULT 0,
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    ended_at timestamp without time zone,
    CONSTRAINT mentor_no_self_check CHECK (mentor_user_id <> apprentice_user_id)
);
CREATE UNIQUE INDEX mentor_one_active_apprentice_idx
    ON attendance.mentor_relationships (apprentice_user_id) WHERE ended_at IS NULL;
CREATE INDEX mentor_relationship_mentor_idx
    ON attendance.mentor_relationships (mentor_user_id, relationship_id);
CREATE INDEX mentor_relationship_apprentice_idx
    ON attendance.mentor_relationships (apprentice_user_id, relationship_id);

CREATE TABLE attendance.mentor_messages (
    message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relationship_id bigint NOT NULL REFERENCES attendance.mentor_relationships(relationship_id) ON DELETE CASCADE,
    sender_user_id bigint NOT NULL REFERENCES attendance.users(user_id) ON DELETE CASCADE,
    request_id varchar(36) NOT NULL,
    body varchar(2000) NOT NULL,
    is_removed boolean NOT NULL DEFAULT false,
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    UNIQUE (relationship_id, sender_user_id, request_id),
    CONSTRAINT mentor_message_body_check CHECK (length(trim(body)) > 0)
);
CREATE INDEX mentor_messages_relationship_idx ON attendance.mentor_messages (relationship_id, message_id);
CREATE INDEX mentor_messages_sender_idx ON attendance.mentor_messages (sender_user_id, created_at);

ALTER TABLE attendance.exercise_research_records
    ADD COLUMN revision integer NOT NULL DEFAULT 1,
    ADD COLUMN updated_at timestamp without time zone,
    ADD COLUMN updated_by_user_id bigint REFERENCES attendance.users(user_id) ON DELETE SET NULL;
CREATE INDEX exercise_research_records_editor_idx
    ON attendance.exercise_research_records (updated_by_user_id);

CREATE TABLE attendance.exercise_research_revisions (
    revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id bigint NOT NULL REFERENCES attendance.exercise_research_records(record_id) ON DELETE CASCADE,
    revision integer NOT NULL,
    editor_user_id bigint REFERENCES attendance.users(user_id) ON DELETE SET NULL,
    previous_content varchar(2000) NOT NULL,
    content varchar(2000) NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    UNIQUE (record_id, revision)
);
CREATE INDEX exercise_research_revisions_editor_idx
    ON attendance.exercise_research_revisions (editor_user_id);

-- Cookie authentication and participant checks are enforced by FastAPI.
-- No Supabase Data API clients may access these private tables or sequences.
ALTER TABLE attendance.mentor_relationships ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance.mentor_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance.exercise_research_revisions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON attendance.mentor_relationships, attendance.mentor_messages,
    attendance.exercise_research_revisions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE attendance.mentor_relationships_relationship_id_seq,
    attendance.mentor_messages_message_id_seq, attendance.exercise_research_revisions_revision_id_seq
    FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON attendance.mentor_relationships,
    attendance.mentor_messages, attendance.exercise_research_revisions TO attendance_api;
GRANT USAGE, SELECT ON SEQUENCE attendance.mentor_relationships_relationship_id_seq,
    attendance.mentor_messages_message_id_seq, attendance.exercise_research_revisions_revision_id_seq
    TO attendance_api;
CREATE POLICY backend_access ON attendance.mentor_relationships
    FOR ALL TO attendance_api USING (true) WITH CHECK (true);
CREATE POLICY backend_access ON attendance.mentor_messages
    FOR ALL TO attendance_api USING (true) WITH CHECK (true);
CREATE POLICY backend_access ON attendance.exercise_research_revisions
    FOR ALL TO attendance_api USING (true) WITH CHECK (true);

COMMENT ON TABLE attendance.mentor_relationships IS
    'Explicit apprentice consent grants mentor access to all notes and reports until either party ends the relationship.';
COMMENT ON TABLE attendance.mentor_messages IS
    'Private participant-only coaching conversations; ended relationships are read-only and never inherited by a new mentor.';
COMMENT ON TABLE attendance.exercise_research_revisions IS
    'Original and revised text for every research-note edit; account deletion removes owned notes and anonymizes editor references.';

RESET lock_timeout;
RESET statement_timeout;
