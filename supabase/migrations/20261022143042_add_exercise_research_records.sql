-- Version matches the applied Supabase production migration history.
SET lock_timeout = '5s';
SET statement_timeout = '15s';

CREATE TABLE attendance.exercise_research_records (
    record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES attendance.users(user_id) ON DELETE CASCADE,
    exercise_id bigint REFERENCES attendance.exercise_items(exercise_id) ON DELETE CASCADE,
    shared_exercise_id bigint REFERENCES attendance.shared_exercise_items(exercise_id) ON DELETE CASCADE,
    content varchar(2000) NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT exercise_research_records_exercise_check CHECK (
        (exercise_id IS NOT NULL AND shared_exercise_id IS NULL)
        OR (exercise_id IS NULL AND shared_exercise_id IS NOT NULL)
    ),
    CONSTRAINT exercise_research_records_content_check CHECK (length(trim(content)) > 0)
);

CREATE INDEX exercise_research_records_custom_idx
    ON attendance.exercise_research_records (user_id, exercise_id, created_at DESC, record_id DESC);
CREATE INDEX exercise_research_records_shared_idx
    ON attendance.exercise_research_records (user_id, shared_exercise_id, created_at DESC, record_id DESC);

-- Private FastAPI cookie authentication uses the backend database role.
-- This schema is not exposed through the Supabase Data API.
ALTER TABLE attendance.exercise_research_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON attendance.exercise_research_records FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE attendance.exercise_research_records_record_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON attendance.exercise_research_records TO attendance_api;
GRANT USAGE, SELECT ON SEQUENCE attendance.exercise_research_records_record_id_seq TO attendance_api;
CREATE POLICY backend_access ON attendance.exercise_research_records
    FOR ALL TO attendance_api USING (true) WITH CHECK (true);

COMMENT ON TABLE attendance.exercise_research_records IS
    'Private exercise technique notes per user; latest is ordered by creation time then record_id, never edit time.';

RESET lock_timeout;
RESET statement_timeout;
